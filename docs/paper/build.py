"""Merge the per-track paper sections into one draft (T3, #23).

    python docs/paper/build.py            # writes docs/paper/draft.md
    python docs/paper/build.py --check    # exit 1 if draft.md is stale

The section files stay the place to edit; ``draft.md`` is generated. Order: abstract,
introduction and related work (``shared.md``), one chapter per track, then the shared
limitations and conclusion, then the bibliography. Each file's own H1 becomes a chapter
heading and its ``##`` sections are demoted one level. Working lists for the authors
("Open items", "Figures and tables for the merged draft") are left out.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "draft.md"
TITLE = "ORIGIN-T: contamination-caused degradation on a ground-truth testbed (merged draft)"
TRACKS = ("track_a.md", "track_b.md", "track_c.md")
SKIP = ("Open items", "Figures and tables for the merged draft")


def _text(name: str) -> str:
    return (HERE / name).read_text(encoding="utf-8").replace("\r\n", "\n")


def sections(text: str) -> tuple[str, list[tuple[str, str]]]:
    """``(h1 title, [(## heading, body), ...])``; text before the first ``##`` goes with the H1."""
    lines = text.split("\n")
    title = lines[0].lstrip("# ").strip()
    parts: list[tuple[str, str]] = []
    head, buf = "", []
    for line in lines[1:]:
        if line.startswith("## "):
            parts.append((head, "\n".join(buf).strip()))
            head, buf = line[3:].strip(), []
        else:
            buf.append(line)
    parts.append((head, "\n".join(buf).strip()))
    return title, parts


def _bare(heading: str) -> str:
    return re.sub(r"^\d+\.\s*", "", heading)


def _demote(body: str) -> str:
    return re.sub(r"^(#{3,5}) ", lambda m: "#" + m.group(1) + " ", body, flags=re.M)


def build() -> str:
    _, shared = sections(_text("shared.md"))
    by_name = {_bare(h): b for h, b in shared if h}
    out = [f"# {TITLE}", "",
           "*Generated by `python docs/paper/build.py` from the section files in `docs/paper/`. "
           "Edit those, not this file.*", ""]
    out += ["## Abstract", "", by_name["Abstract"], ""]
    n = 0
    for name in ("Introduction", "Related work"):
        n += 1
        out += [f"## {n}. {name}", "", _demote(by_name[name]), ""]
    for track in TRACKS:
        title, parts = sections(_text(track))
        n += 1
        out += [f"## {n}. {re.sub(r' [(]draft for T3, #23[)]$', '', title)}", ""]
        intro = parts[0][1]
        if intro:
            out += [intro, ""]
        k = 0
        for head, body in parts[1:]:
            if any(s in head for s in SKIP):
                continue
            k += 1
            out += [f"### {n}.{k} {_bare(head)}", "", _demote(body), ""]
    for name in ("Limitations (shared)", "Conclusion"):
        n += 1
        out += [f"## {n}. {name.replace(' (shared)', '')}", "", _demote(by_name[name]), ""]
    _, bib = sections(_text("bibliography.md"))
    out += ["## References", ""]
    for head, body in bib:
        if any(s in head for s in SKIP):
            continue
        if head:
            out += [f"### {head}", ""]
        if body:
            out += [_demote(body), ""]
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--check", action="store_true", help="fail if draft.md differs from a fresh build")
    args = p.parse_args(argv)
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("docs/paper/draft.md is stale: run python docs/paper/build.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(HERE.parent.parent)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
